CREATE FUNCTION pingup_message_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 -- Per-chat lock held until COMMIT: sequence cursor cannot skip a late commit.
 PERFORM pg_advisory_xact_lock(hashtextextended('chat:' || NEW.conversation_id::text,0));
 NEW.change_seq := nextval('message_changes_seq');
 RETURN NEW;
END $$;
CREATE TRIGGER message_change BEFORE INSERT OR UPDATE ON messages FOR EACH ROW EXECUTE FUNCTION pingup_message_change();
