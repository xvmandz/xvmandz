CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE CHECK(username=lower(username)),
    name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    session_version BIGINT NOT NULL DEFAULT 1,
    role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin')),
    bio TEXT NOT NULL DEFAULT '',
    location TEXT NOT NULL DEFAULT '',
    website TEXT NOT NULL DEFAULT '',
    accent TEXT NOT NULL DEFAULT '#a78bfa',
    avatar_file_id BIGINT,
    locale TEXT NOT NULL DEFAULT 'ru' CHECK(locale IN ('ru','uk','en')),
    theme TEXT NOT NULL DEFAULT 'dark' CHECK(theme IN ('dark','light','system')),
    last_seen BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL CHECK(type IN ('direct','group','channel','saved')),
    name TEXT NOT NULL DEFAULT '',
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    direct_key TEXT UNIQUE,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    slug TEXT UNIQUE,
    invite_token TEXT UNIQUE,
    visibility TEXT NOT NULL DEFAULT 'private' CHECK(visibility IN ('private','public')),
    avatar_file_id BIGINT
);
CREATE TABLE IF NOT EXISTS conversation_members (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_message_id BIGINT NOT NULL DEFAULT 0,
    notification_mode TEXT NOT NULL DEFAULT 'all' CHECK(notification_mode IN ('all','mentions','none')),
    pinned BIGINT NOT NULL DEFAULT 0 CHECK(pinned IN (0,1)),
    PRIMARY KEY (conversation_id,user_id)
);
CREATE INDEX IF NOT EXISTS members_user ON conversation_members(user_id,conversation_id);
CREATE TABLE IF NOT EXISTS files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    disk_name TEXT NOT NULL UNIQUE,
    original_name TEXT NOT NULL,
    mime TEXT NOT NULL,
    size BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text TEXT NOT NULL DEFAULT '',
    kind TEXT NOT NULL DEFAULT 'text' CHECK(kind IN ('text','file','voice','call')),
    file_id BIGINT REFERENCES files(id) ON DELETE SET NULL,
    reply_to BIGINT REFERENCES messages(id) ON DELETE SET NULL,
    forwarded_from BIGINT REFERENCES messages(id) ON DELETE SET NULL,
    client_id TEXT NOT NULL,
    pinned BIGINT NOT NULL DEFAULT 0 CHECK(pinned IN (0,1)),
    edited BIGINT NOT NULL DEFAULT 0 CHECK(edited IN (0,1)),
    deleted BIGINT NOT NULL DEFAULT 0 CHECK(deleted IN (0,1)),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE(sender_id,client_id)
);
CREATE INDEX IF NOT EXISTS messages_conversation_id ON messages(conversation_id,id);
CREATE INDEX IF NOT EXISTS messages_conversation_updated ON messages(conversation_id,updated_at);
CREATE TABLE IF NOT EXISTS reactions (
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    emoji TEXT NOT NULL,
    PRIMARY KEY(message_id,user_id,emoji)
);
CREATE TABLE IF NOT EXISTS typing (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL,
    PRIMARY KEY(conversation_id,user_id)
);
CREATE TABLE IF NOT EXISTS rate_limits (
    bucket TEXT PRIMARY KEY,
    attempts BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);


-- Signaling metadata only. Media travels between browsers over encrypted WebRTC.
CREATE TABLE IF NOT EXISTS calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    callee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK(kind IN ('audio','video')),
    status TEXT NOT NULL DEFAULT 'ringing' CHECK(status IN ('ringing','active','ended','rejected')),
    created_at BIGINT NOT NULL,
    answered_at BIGINT,
    ended_at BIGINT,
    end_reason TEXT,
    caller_device TEXT NOT NULL DEFAULT '',
    callee_device TEXT NOT NULL DEFAULT '',
    caller_heartbeat BIGINT NOT NULL,
    callee_heartbeat BIGINT NOT NULL,
    CHECK(caller_id <> callee_id)
);
CREATE INDEX IF NOT EXISTS calls_caller ON calls(caller_id,status,id);
CREATE INDEX IF NOT EXISTS calls_callee ON calls(callee_id,status,id);
CREATE TABLE IF NOT EXISTS call_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id BIGINT NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type TEXT NOT NULL CHECK(type IN ('offer','answer','candidate')),
    payload TEXT NOT NULL,
    negotiation BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS call_signals_call ON call_signals(call_id,id);
CREATE UNIQUE INDEX IF NOT EXISTS call_sdp_once ON call_signals(call_id,sender_id,type,negotiation) WHERE type IN ('offer','answer');

CREATE TABLE IF NOT EXISTS notification_settings (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 settings TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS notification_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN ('message','mention','call')),
 message_id BIGINT REFERENCES messages(id) ON DELETE CASCADE,
 call_id BIGINT REFERENCES calls(id) ON DELETE CASCADE,
 dedup_key TEXT NOT NULL,
 created_at BIGINT NOT NULL,
 UNIQUE(user_id,dedup_key)
);
CREATE INDEX IF NOT EXISTS notification_events_user ON notification_events(user_id,id);
CREATE TABLE IF NOT EXISTS push_subscriptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 endpoint TEXT NOT NULL,
 endpoint_hash TEXT NOT NULL UNIQUE,
 p256dh TEXT NOT NULL,
 auth TEXT NOT NULL,
 session_hash TEXT NOT NULL,
 session_version BIGINT NOT NULL,
 expires_at BIGINT NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS push_subscriptions_user ON push_subscriptions(user_id);
CREATE TABLE IF NOT EXISTS push_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES notification_events(id) ON DELETE CASCADE,
 subscription_id BIGINT NOT NULL REFERENCES push_subscriptions(id) ON DELETE CASCADE,
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','processing','sent','cancelled','failed')),
 attempts BIGINT NOT NULL DEFAULT 0,
 available_at BIGINT NOT NULL,
 lease_until BIGINT NOT NULL DEFAULT 0,
 error_code TEXT,
 UNIQUE(event_id,subscription_id)
);
CREATE INDEX IF NOT EXISTS push_deliveries_pending ON push_deliveries(status,available_at,lease_until);

